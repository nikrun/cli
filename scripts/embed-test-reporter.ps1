<#
.SYNOPSIS
    Regenerates src/nik.test.reporter.inc from src/runner/nikrun_test_reporter.pas.

.DESCRIPTION
    The reporter unit is compiled into every generated `nik test` runner. Its source of truth is
    src/runner/nikrun_test_reporter.pas; this script embeds it as a Pascal string constant so the
    single `nik` binary can write it into .nik/cache at test time.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$CliRoot = Split-Path -Parent $PSScriptRoot
$Source  = Join-Path $CliRoot 'src/runner/nikrun_test_reporter.pas'
$Target  = Join-Path $CliRoot 'src/nik.test.reporter.inc'

$lines = [System.IO.File]::ReadAllLines($Source)
$out = New-Object System.Collections.Generic.List[string]
$out.Add('{ GENERATED by scripts/embed-test-reporter.ps1 from src/runner/nikrun_test_reporter.pas - do not edit. }')
$out.Add('TEST_REPORTER_SOURCE =')
for ($i = 0; $i -lt $lines.Count; $i++) {
    $escaped = $lines[$i].Replace("'", "''")
    $suffix = if ($i -lt $lines.Count - 1) { " + LineEnding +" } else { ";" }
    $out.Add("  '$escaped'$suffix")
}
[System.IO.File]::WriteAllText($Target, (($out -join "`r`n") + "`r`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $Target ($($lines.Count) source lines)"
